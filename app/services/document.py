"""Pure function: structured state -> draft document (Markdown). No LLM involved."""
from __future__ import annotations

from app.domain.questions import display_value
from app.domain.state import FieldKey, FieldStatus, WishesState

DISCLAIMER = ("**FICTIONAL DOCUMENT. NOT LEGAL ADVICE.** This draft was generated by a demo "
              "application and has no legal effect.")
MISSING = "[not yet provided]"


def _text(state: WishesState, key: FieldKey) -> str:
    status = state.status(key)
    if status == FieldStatus.UNKNOWN:
        return MISSING
    text = display_value(state.value(key))
    return f"{text} [unconfirmed]" if status == FieldStatus.UNCONFIRMED else text


def _list_section(state: WishesState, key: FieldKey, empty_text: str) -> list[str]:
    if state.status(key) == FieldStatus.UNKNOWN:
        return [MISSING]
    items = state.value(key)
    suffix = " [unconfirmed]" if state.status(key) == FieldStatus.UNCONFIRMED else ""
    if not items:
        return [empty_text + suffix]
    return [f"- {item}{suffix}" for item in items]


def render_document(state: WishesState) -> str:
    done = state.is_complete()
    lines = [
        "# Personal Wishes Document",
        f"*Status: {'complete draft' if done else 'INCOMPLETE DRAFT'}*",
        "",
        f"> {DISCLAIMER}",
        "",
        "## 1. Personal details",
        f"- Full name: {_text(state, FieldKey.FULL_NAME)}",
        f"- Home address: {_text(state, FieldKey.HOME_ADDRESS)}",
        "",
        "## 2. Scope",
    ]
    worldwide = state.value(FieldKey.COVERS_WORLDWIDE_ASSETS)
    if state.status(FieldKey.COVERS_WORLDWIDE_ASSETS) == FieldStatus.UNKNOWN:
        lines.append(MISSING)
    else:
        sentence = ("This document covers my assets worldwide." if worldwide
                    else "This document does not cover assets worldwide.")
        if state.status(FieldKey.COVERS_WORLDWIDE_ASSETS) == FieldStatus.UNCONFIRMED:
            sentence += " [unconfirmed]"
        lines.append(sentence)

    lines += ["", "## 3. Children"]
    has_children = state.value(FieldKey.HAS_CHILDREN)
    unconfirmed = " [unconfirmed]" if state.status(FieldKey.HAS_CHILDREN) == FieldStatus.UNCONFIRMED else ""
    if state.status(FieldKey.HAS_CHILDREN) == FieldStatus.UNKNOWN:
        lines.append(MISSING)
    elif has_children is False:
        lines.append(f"I have no children.{unconfirmed}")
    else:
        lines.append(f"I have children.{unconfirmed}")
        lines += _list_section(state, FieldKey.CHILDREN_NAMES, "[no names given]")

    lines += [
        "",
        "## 4. Executor",
        f"I appoint {_text(state, FieldKey.EXECUTOR_NAME)}, my {_text(state, FieldKey.EXECUTOR_RELATIONSHIP)}, to act as my executor.",
        "",
        "## 5. Specific gifts",
        *_list_section(state, FieldKey.SPECIFIC_GIFTS, "No specific gifts."),
        "",
        "## 6. Additional wishes",
        *_list_section(state, FieldKey.ADDITIONAL_WISHES, "No additional wishes."),
        "",
        "---",
        f"> {DISCLAIMER}",
    ]
    return "\n".join(lines)
